import cv2
import numpy as np
from matplotlib import pyplot as plt

def show_image(title,img,cmap=None):
    plt.figure(figsize=(5,5))
    plt.title(title)
    if cmap:
      plt.imshow(img,cmap=cmap)
    else:
      plt.imshow(cv2.cvtColor(img,cv2.COLOR_BGR2RGB))
    plt.axis('off')
    plt.show()

img1=cv2.imread("/content/drive/MyDrive/Colab Notebooks/nature1.jpg")
img2=cv2.imread("/content/drive/MyDrive/Colab Notebooks/nature2.jpg")

show_image("MOUNTAINS",img1)
show_image("RIVER",img2)

print(img1.shape)
print(img2.shape)

img2=cv2.resize(img2,(img1.shape[1],img1.shape[0]))

cropped_img = img1[50:800, 100:700]
show_image("Cropped Image", cropped_img)

added_img=cv2.addWeighted(img1,0.5,img2,0.5,0)
show_image("Arthematic Addition(Blending)",added_img)

subtracted_img=cv2.subtract(img1,img2)
show_image("Arthematic Subtraction",subtracted_img)

rectangle=np.zeros((img1.shape[0],img1.shape[1]),dtype="uint8")
