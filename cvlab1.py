bitwise_not=cv2.bitwise_not(rectangle,circle)
show_image("Bitwise NOT",bitwise_not,cmap='gray')

def rotation_func(angle_in_radians):
    return np.array([
        [np.cos(angle_in_radians), np.sin(angle_in_radians)],
        [-np.sin(angle_in_radians), np.cos(angle_in_radians)]
    ])

gray = cv2.cvtColor(img1, cv2.COLOR_BGR2GRAY)

show_image("Gray Image", gray, cmap="gray")

m, n = gray.shape

rotation_matrix = rotation_func(np.pi / 2)

rotated_image = np.zeros((m, n), dtype=gray.dtype)

for i in range(m):
    for j in range(n):

        x = i - m // 2
        y = j - n // 2

        a, b = rotation_matrix @ np.array([x, y])

        a = int(round(a))
        b = int(round(b))

        if (0 <= a + m // 2 < m) and (0 <= b + n // 2 < n):
            rotated_image[a + m // 2, b + n // 2] = gray[i, j]

show_image("Rotated Image", rotated_image, cmap="gray")

(h, w) = img1.shape[:2]

center = (w // 2, h // 2)

M = cv2.getRotationMatrix2D(center, 90, 1)

rotated = cv2.warpAffine(img1, M, (w, h))

show_image("OpenCV Rotated Image", rotated)